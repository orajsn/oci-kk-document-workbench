-- Run once as the schema owner. Activate a scope separately.
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
CREATE TABLE KK_OWNER.KK_NIK_ROUTE_CONTROL (
 scope_id VARCHAR2(64 CHAR) PRIMARY KEY, enabled_from TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL);

CREATE TABLE KK_OWNER.KK_NIK_ROUTE_RUNS (
 job_id VARCHAR2(36 CHAR) PRIMARY KEY REFERENCES KK_OWNER.KK_JOBS(job_id),
 job_version NUMBER(10) NOT NULL, member_count NUMBER(5) NOT NULL, flagged NUMBER(5) NOT NULL,
 cleared NUMBER(5) NOT NULL, review_count NUMBER(5) NOT NULL, crop_reads NUMBER(5) NOT NULL,
 report_json CLOB NOT NULL CHECK(report_json IS JSON), finished_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT kk_nik_route_counts_ck CHECK(flagged=cleared+review_count AND flagged<=member_count AND crop_reads<=flagged));
GRANT SELECT ON KK_OWNER.KK_NIK_ROUTE_CONTROL TO KK_RUNTIME_ROLE;
GRANT SELECT, INSERT ON KK_OWNER.KK_NIK_ROUTE_RUNS TO KK_RUNTIME_ROLE;
