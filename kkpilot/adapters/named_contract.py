"""Named model values with explicit evidence, expanded through strict domain 1.0."""

import json
from pathlib import Path

from .compact_contract import (
    STATUS_CODES, WIRE_VERSION as COMPACT_WIRE_VERSION,
    build_wire_schema, build_cohere_wire_schema, expand_response,
)
from ..validation import HOUSEHOLD_FIELDS, MEMBER_FIELDS, MAX_MEMBERS, MAX_EXTRACTION_BYTES, PayloadError

WIRE_VERSION = "named-1.0"
PROMPT_VERSION = "1.2"
ROOT = Path(__file__).resolve().parents[2]


def _require(condition, message):
    if not condition:
        raise PayloadError("INVALID_NAMED_EXTRACTION", message)


def _value_schema(fields, *, server=False):
    properties = {}
    for field in fields:
        if field == "row_number":
            properties[field] = {"type": ["integer", "null"]} if server else {"type": "integer", "minimum": 1, "maximum": MAX_MEMBERS}
        else:
            properties[field] = {"type": ["string", "null"]}
            if not server:
                properties[field]["maxLength"] = 2000
    return {"type": "object", "additionalProperties": False, "required": list(fields), "properties": properties}


def _named_schema(*, server):
    schema = build_cohere_wire_schema() if server else build_wire_schema()
    schema["properties"]["wire_version"] = {"type": "string", "const": WIRE_VERSION}
    schema["properties"]["household"]["properties"]["v"] = _value_schema(HOUSEHOLD_FIELDS, server=server)
    schema["properties"]["members"]["items"]["properties"]["v"] = _value_schema(MEMBER_FIELDS, server=server)
    if not server:
        schema["$id"] = "urn:kk:kk-extraction:" + WIRE_VERSION
        schema["title"] = "Named KK model values; explicit ordered evidence; domain schema 1.0"
        schema["$comment"] = "Generated by named_contract.build_named_wire_schema(). Named values use canonical field keys; evidence order comes from validation.py."
    return schema


def build_named_wire_schema():
    return _named_schema(server=False)


def build_named_cohere_schema():
    """Required property names/types prevent positional value shifts.

    Unsupported server bounds remain enforced locally. Null row_number is an
    expressible native failure marker; strict expansion deliberately rejects it.
    """
    return _named_schema(server=True)


def build_named_prompt():
    instructions = (ROOT / "schemas/named-prompt.txt").read_text(encoding="utf-8").rstrip()
    orders = {"household.e": list(HOUSEHOLD_FIELDS), "members[].e": list(MEMBER_FIELDS)}
    return (instructions + "\nPROMPT_VERSION: " + PROMPT_VERSION + "\nWIRE_VERSION: " + WIRE_VERSION
            + "\nEVIDENCE ORDER (zero-based positions, also used by notes/flags): " + json.dumps(orders, separators=(",", ":"))
            + "\nEVIDENCE CODES: " + json.dumps(STATUS_CODES, separators=(",", ":"))
            + "\nJSON SCHEMA FOR GENERATION: " + json.dumps(build_named_cohere_schema(), separators=(",", ":")))


def expand_named_response(response):
    """Map exact names to canonical positions without repairing values or states."""
    _require(isinstance(response, dict), "Named response must be an object.")
    required = {"wire_version", "layout_family", "household", "members"}
    _require(required <= set(response) <= required | {"notes", "flags"}, "Named response has missing or unsupported top-level fields.")
    _require(response["wire_version"] == WIRE_VERSION, "Unsupported named wire version.")

    def convert(section, fields, message):
        _require(isinstance(section, dict) and set(section) == {"v", "e"}, "Each named section must contain only v and e.")
        values = section["v"]
        _require(isinstance(values, dict) and set(values) == set(fields), message)
        return {"v": [values[field] for field in fields], "e": section["e"]}

    _require(isinstance(response["members"], list) and len(response["members"]) <= MAX_MEMBERS,
             "Members must be an array of at most 100 rows.")
    compact = dict(response)
    compact["wire_version"] = COMPACT_WIRE_VERSION
    compact["household"] = convert(response["household"], HOUSEHOLD_FIELDS, "Named household value keys must match canonical fields.")
    compact["members"] = [convert(member, MEMBER_FIELDS, "Named member value keys must match canonical fields.")
                          for member in response["members"]]
    result = expand_response(compact)
    encoded = json.dumps(response, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode("utf-8")
    _require(len(encoded) <= MAX_EXTRACTION_BYTES, "Named response exceeds the 2 MiB local record limit.")
    return result
