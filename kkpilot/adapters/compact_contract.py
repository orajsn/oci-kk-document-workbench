"""Optional compact model wire format; deterministic expansion to domain schema 1.0.

No model calls, acceptance decisions, OCR repairs or inferred evidence occur here.
Parse raw JSON with the adapter's duplicate-key-rejecting parser before expansion.
"""

from __future__ import annotations

import json
from pathlib import Path

from ..validation import (
    EVIDENCE_STATUSES, HOUSEHOLD_FIELDS, MAX_EXTRACTION_BYTES, MAX_MEMBERS,
    MEMBER_FIELDS, PayloadError, assert_valid_payload,
)

WIRE_VERSION = "compact-1.0"
PROMPT_VERSION = "1.1"
DOMAIN_SCHEMA_VERSION = "1.0"
ROOT = Path(__file__).resolve().parents[2]
STATUS_CODES = {
    "R": "READABLE",
    "B": "BLANK_ON_DOCUMENT",
    "U": "UNREADABLE",
    "C": "CROPPED",
    "L": "NOT_PRESENT_IN_LAYOUT",
    "A": "AMBIGUOUS",
    "N": "NOT_REVIEWED",
}


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise PayloadError("INVALID_COMPACT_EXTRACTION", message)


def _text(value: object, maximum: int, *, nullable: bool = False) -> bool:
    if value is None:
        return nullable
    if not isinstance(value, str) or len(value) > maximum or "\x00" in value:
        return False
    try:
        value.encode("utf-8")
    except UnicodeError:
        return False
    return True


def build_wire_schema() -> dict:
    """Generate the checked-in schema from the domain's authoritative field order."""
    if set(STATUS_CODES.values()) != set(EVIDENCE_STATUSES):
        raise RuntimeError("Compact evidence mapping must match domain evidence states.")

    def vector(fields: tuple[str, ...], *, member: bool) -> dict:
        values = []
        for field in fields:
            item = {"title": field, "type": ["string", "null"], "maxLength": 2000}
            if member and field == "row_number":
                item = {"title": field, "type": "integer", "minimum": 1, "maximum": MAX_MEMBERS}
            values.append(item)
        return {
            "type": "object", "additionalProperties": False, "required": ["v", "e"],
            "properties": {
                "v": {"type": "array", "prefixItems": values, "items": False,
                      "minItems": len(fields), "maxItems": len(fields)},
                "e": {"type": "string", "minLength": len(fields), "maxLength": len(fields),
                      "pattern": "^[" + "".join(STATUS_CODES) + "]{" + str(len(fields)) + r"}(?![\s\S])"},
            },
        }

    reference = {"type": "string", "maxLength": 200,
                 "pattern": r"^(h\.(0|[1-9][0-9]*)|m\.[1-9][0-9]*\.(0|[1-9][0-9]*))(?![\s\S])"}
    flag_reference = {**reference, "pattern":
        r"^(layout_family|h\.(0|[1-9][0-9]*)|m\.[1-9][0-9]*\.(0|[1-9][0-9]*))(?![\s\S])"}
    bounded_note = {"type": "string", "maxLength": 500}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "urn:kk:kk-extraction:" + WIRE_VERSION,
        "$comment": "Generated by compact_contract.build_wire_schema(); field order comes from validation.py. "
                    "Expansion also checks unique printed row identifiers, references, Unicode and UTF-8 size.",
        "title": "Optional compact KK model response; expands to domain schema 1.0",
        "type": "object", "additionalProperties": False,
        "required": ["wire_version", "layout_family", "household", "members"],
        "properties": {
            "wire_version": {"const": WIRE_VERSION},
            "layout_family": {"enum": ["modern", "legacy", "unknown"]},
            "household": vector(HOUSEHOLD_FIELDS, member=False),
            "members": {"type": "array", "maxItems": MAX_MEMBERS,
                        "items": vector(MEMBER_FIELDS, member=True)},
            "notes": {"type": "array", "maxItems": 5000, "items": {
                "type": "array", "prefixItems": [reference, bounded_note],
                "items": False, "minItems": 2, "maxItems": 2}},
            "flags": {"type": "array", "maxItems": 500, "items": {
                "type": "array", "prefixItems": [flag_reference,
                    {"type": "string", "maxLength": 80}, bounded_note],
                "items": False, "minItems": 3, "maxItems": 3}},
        },
    }


def build_prompt() -> str:
    """Build prompt 1.1 with no sample identities or reference-answer values."""
    instructions = (ROOT / "schemas" / "compact-prompt.txt").read_text(encoding="utf-8")
    orders = {"household.v": list(HOUSEHOLD_FIELDS), "members[].v": list(MEMBER_FIELDS)}
    return (
        instructions.rstrip()
        + "\nPROMPT_VERSION: " + PROMPT_VERSION
        + "\nWIRE_VERSION: " + WIRE_VERSION
        + "\nFIELD ORDER (zero-based positions): " + json.dumps(orders, separators=(",", ":"))
        + "\nEVIDENCE CODES: " + json.dumps(STATUS_CODES, separators=(",", ":"))
        + "\nJSON SCHEMA: " + json.dumps(build_wire_schema(), separators=(",", ":"))
    )


def build_cohere_wire_schema() -> dict:
    """Project the strict wire schema into the tested OCI Cohere subset.

    Matches the synthetic v6 service probe. Server constraints are weaker:
    tuple positions and size/range bounds remain enforced only by the prompt
    and expand_response. This projection never changes the local wire schema.
    """
    omitted = {"$schema", "$id", "$comment", "title", "prefixItems", "minItems", "maxItems",
               "minLength", "maxLength", "minimum", "maximum"}

    def compatible(value):
        if isinstance(value, dict):
            result = {
                key: (child.replace(r"(?![\s\S])", "").removeprefix("^").removesuffix("$")
                      if key == "pattern" else compatible(child))
                for key, child in value.items() if key not in omitted
            }
            if "type" not in result and ("enum" in result or "const" in result):
                result["type"] = "string"
            if "prefixItems" in value:
                kinds = []
                for item in value["prefixItems"]:
                    types = item.get("type", [])
                    for kind in types if isinstance(types, list) else [types]:
                        if kind not in kinds:
                            kinds.append(kind)
                result["items"] = {"type": kinds if len(kinds) > 1 else kinds[0]}
            return result
        if isinstance(value, list):
            return [compatible(child) for child in value]
        return value

    return compatible(build_wire_schema())


def build_cohere_prompt() -> str:
    """Keep the native decoder's deliberate failure path expressible.

    Native required top-level keys cannot emit the ordinary {} rejection
    marker. A retained member row with null ID is allowed by the server union
    but intentionally rejected by the unchanged local domain validator.
    """
    replacements = {
        "If ANY populated member row has an unreadable or missing printed row identifier, return exactly {} for the entire image.":
            "If ANY populated member row has an unreadable or missing printed row identifier, retain that populated row, "
            "set its row_number value to null, and explicitly supply the evidence code observed for that identifier. "
            "Add a layout_family flag with code ROW_IDENTIFIER_REVIEW. Do not invent a row number or omit the row.",
        "Every position is required, including nulls and the integer row_number; never shift fields or shorten arrays.":
            "Every position is required, including nulls and row_number; never shift fields or shorten arrays.",
        "Include every populated member row exactly once, with a unique printed row_number from 1 to 100.":
            "Include every populated member row exactly once. Readable printed row numbers must be unique integers from 1 to 100. "
            "A null row_number is allowed ONLY as the deliberate native failure marker described above.",
        "The mandatory integer row_number cannot use a null-required state; an unavailable printed row identifier requires review, never an invented integer.":
            "For an unavailable printed row identifier, the native failure marker is null with an explicitly supplied evidence state. "
            "This marker deliberately fails local ROW_IDENTIFIER validation and requires review; never substitute an invented integer.",
    }
    prompt = build_prompt()
    for original, replacement in replacements.items():
        if prompt.count(original) != 1:
            raise RuntimeError("Native failure instructions require a matching compact prompt revision.")
        prompt = prompt.replace(original, replacement)
    return prompt


def expand_response(response: dict) -> dict:
    """Validate wire structure and expand without changing values or evidence states.

    Evidence/value conflicts and uncertain data remain for validate_payload and
    human review. This function does not approve a draft or infer a missing state.
    """
    _require(isinstance(response, dict), "Compact response must be an object.")
    required = {"wire_version", "layout_family", "household", "members"}
    _require(required <= set(response) <= required | {"notes", "flags"},
             "Compact response has missing or unsupported top-level fields.")
    _require(response["wire_version"] == WIRE_VERSION, "Unsupported compact wire version.")
    _require(response["layout_family"] in ("modern", "legacy", "unknown"), "Invalid layout family.")
    members = response["members"]
    _require(isinstance(members, list) and len(members) <= MAX_MEMBERS,
             "Members must be an array of at most 100 rows.")
    evidence: list[dict] = []
    references: dict[str, dict] = {}

    def expand_vector(vector: object, fields: tuple[str, ...], prefix: str,
                      section: str, *, member: bool = False) -> dict:
        _require(isinstance(vector, dict) and set(vector) == {"v", "e"},
                 "Each compact vector must contain only v and e.")
        values, states = vector["v"], vector["e"]
        _require(isinstance(values, list) and len(values) == len(fields), "Wrong value vector length.")
        _require(isinstance(states, str) and len(states) == len(fields)
                 and all(code in STATUS_CODES for code in states), "Invalid or missing evidence states.")
        result = {}
        for field, value in zip(fields, values):
            if member and field == "row_number":
                _require(type(value) is int and 1 <= value <= MAX_MEMBERS,
                         "Printed member row number must be an integer from 1 to 100.")
            else:
                _require(_text(value, 2000, nullable=True), "Values must be bounded strings or null.")
            result[field] = value
        row_number = result["row_number"] if member else None
        for position, (field, state) in enumerate(zip(fields, states)):
            item = {"path": prefix + field, "status": STATUS_CODES[state], "section": section}
            if member:
                item["row_number"] = row_number
            reference = f"m.{row_number}.{position}" if member else f"h.{position}"
            references[reference] = item
            evidence.append(item)
        return result

    household = expand_vector(response["household"], HOUSEHOLD_FIELDS, "household.", "household")
    expanded_members = []
    seen_rows: set[int] = set()
    for index, member in enumerate(members):
        expanded = expand_vector(member, MEMBER_FIELDS, f"members[{index}].", "members", member=True)
        _require(expanded["row_number"] not in seen_rows, "Duplicate printed member row number.")
        seen_rows.add(expanded["row_number"])
        expanded_members.append(expanded)

    def resolve(reference: object, *, flag: bool = False) -> str:
        _require(_text(reference, 200), "Invalid field reference.")
        if flag and reference == "layout_family":
            return reference
        _require(reference in references, "Field reference must identify a supplied field and printed row.")
        return references[reference]["path"]

    notes = response.get("notes", [])
    _require(isinstance(notes, list) and len(notes) <= 5000, "Notes must be a bounded array.")
    seen_notes: set[str] = set()
    for item in notes:
        _require(isinstance(item, list) and len(item) == 2, "Each note must be [reference, note].")
        path = resolve(item[0])
        _require(path not in seen_notes, "Duplicate evidence note target.")
        _require(_text(item[1], 500), "Invalid evidence note.")
        seen_notes.add(path)
        references[item[0]]["note"] = item[1]

    flags = response.get("flags", [])
    _require(isinstance(flags, list) and len(flags) <= 500, "Flags must be a bounded array.")
    expanded_flags = []
    for item in flags:
        _require(isinstance(item, list) and len(item) == 3, "Each flag must be [reference, code, message].")
        path = resolve(item[0], flag=True)
        _require(_text(item[1], 80) and _text(item[2], 500), "Invalid review flag text.")
        expanded_flags.append({"path": path, "code": item[1], "message": item[2]})

    encoded = json.dumps(response, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode("utf-8")
    _require(len(encoded) <= MAX_EXTRACTION_BYTES, "Compact response exceeds the 2 MiB local record limit.")
    result = {"schema_version": DOMAIN_SCHEMA_VERSION, "layout_family": response["layout_family"],
              "household": household, "members": expanded_members, "field_evidence": evidence,
              "review_flags": expanded_flags}
    assert_valid_payload(result)  # Also bounds expanded UTF-8 bytes, not just the compact wire size.
    return result
